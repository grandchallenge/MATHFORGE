"""RH-A26: independently enumerate S3/A3 first-cohomology local restrictions.

Exact arithmetic over F_p. Tests the quotient-inflation/local-kernel mechanism,
not the original Lean kernel or actual number-field arithmetic.
"""
from itertools import permutations

G = tuple(permutations(range(3)))
IDENT = (0, 1, 2)
S = (1, 0, 2)
T = (0, 2, 1)


def mul(x, y):
    return tuple(x[y[i]] for i in range(3))


def parity(g):
    return sum(g[i] > g[j] for i in range(3) for j in range(i + 1, 3)) % 2


N = {g for g in G if parity(g) == 0}  # A3: normally generated by a 3-cycle


def subgroup(*gens):
    out = {IDENT}
    for _ in range(10):
        nxt = out | {mul(g, h) for g in out for h in gens}
        nxt |= {mul(h, g) for g in out for h in gens}
        if nxt == out:
            break
        out = nxt
    return frozenset(out)


Ds = {subgroup(g) for g in G} | {subgroup(S, T)}
assert len(G) == 6 and len(N) == 3 and len(Ds) == 6
index = {g: i for i, g in enumerate(G)}


def rho(g, p, kind):
    return 1 if kind == "trivial" or parity(g) == 0 else p - 1


def cocycles(p, kind):
    """Exhaustively assign two generator values and enforce every cocycle relation."""
    out = {}
    for zs in range(p):
        for zt in range(p):
            vals = {IDENT: 0}
            frontier = [IDENT]
            consistent = True
            while frontier:
                g = frontier.pop()
                for gen, v in ((S, zs), (T, zt)):
                    h = mul(g, gen)
                    expected = (vals[g] + rho(g, p, kind) * v) % p
                    if h in vals:
                        if vals[h] != expected:
                            consistent = False
                    else:
                        vals[h] = expected
                        frontier.append(h)
            if not consistent:
                continue
            assert len(vals) == len(G)
            assert all(
                vals[mul(g, h)] == (vals[g] + rho(g, p, kind) * vals[h]) % p
                for g in G for h in G
            )
            out[tuple(vals[g] for g in G)] = vals
    return out


def coboundaries(p, kind):
    return {
        tuple((rho(g, p, kind) - 1) * m % p for g in G)
        for m in range(p)
    }


def canonical(x, p, kind):
    return min(
        tuple((a + b) % p for a, b in zip(x, cob))
        for cob in coboundaries(p, kind)
    )


def quotient_cocycles(p, kind):
    a = rho(S, p, kind)  # Q = C2, acting trivially or by sign.
    return [z for z in range(p) if (1 + a) * z % p == 0]


def quotient_coboundaries(p, kind):
    return {(rho(S, p, kind) - 1) * m % p for m in range(p)}


def quotient_classes(p, kind):
    b = quotient_coboundaries(p, kind)
    return {min((z + delta) % p for delta in b) for z in quotient_cocycles(p, kind)}


def inflate(z, p, kind):
    return canonical(tuple(z if parity(g) else 0 for g in G), p, kind)


def local_coboundary(x, D, p, kind):
    return any(
        all(x[index[g]] == (rho(g, p, kind) - 1) * m % p for g in D)
        for m in range(p)
    )


def main():
    cases = nontrivial = excluded = 0
    for p in (2, 3, 5, 7, 11, 13):
        for kind in ("trivial", "sign"):
            full_z = cocycles(p, kind)
            full_h1 = {canonical(c, p, kind) for c in full_z}
            quotient = quotient_classes(p, kind)
            inflated = {inflate(z, p, kind) for z in quotient}
            assert len(inflated) == len(quotient)  # inflation injective
            for D in Ds:
                # Outside-S inertia N=A3 acts trivially, so coboundary=zero on N.
                selmer_full = {
                    canonical(c, p, kind)
                    for c, values in full_z.items()
                    if all(values[n] == 0 for n in N)
                    and local_coboundary(c, D, p, kind)
                }
                # Inside-S local D, mapped to its image in Q=C2.
                selmer_quotient = {
                    inflate(z, p, kind) for z in quotient
                    if not any(parity(g) for g in D)
                    or z in quotient_coboundaries(p, kind)
                }
                assert selmer_full == selmer_quotient, (p, kind, D)
                cases += 1
                if len(selmer_full) > 1:
                    nontrivial += 1
            if p == 3 and kind == "sign":
                # Removing the outside-S inertia condition incorrectly admits
                # two extra H1 classes: this must remain an explicit negative control.
                assert len(full_h1) > len(inflated)
                excluded += len(full_h1) - len(inflated)
    assert cases == 72 and nontrivial > 0 and excluded > 0
    print(
        f"PASS {cases} exact S3/A3 local-Selmer comparisons; "
        f"{nontrivial} nontrivial local cases; "
        f"{excluded} inertia-sensitive excluded classes"
    )


if __name__ == "__main__":
    main()
