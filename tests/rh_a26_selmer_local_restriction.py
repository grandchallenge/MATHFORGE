#!/usr/bin/env python3
"""RH-A26 independent toy Selmer-local-restriction test, exact finite arithmetic.

G=C_n, U'=<m>, D=<d> where m,d divide n, coefficients F_p trivial.
Cocycles Hom(C_n,F_p) are determined by z with n*z=0.
Local kernel at D requires d*z=0.
Restriction sends z to y=m*z in Hom(C_(n/m),F_p).
Intersection U' ∩ D is generated by lcm(m,d) in C_n, so the
local subgroup restriction requires (lcm(m,d)/m)*y=0.

For p not dividing m, assert equality of original and descended
Selmer local kernels. Demonstrates a finite mechanism only, not Galois Sha.
"""
from math import gcd


def divisors(n):
    return [d for d in range(1, n+1) if n % d == 0]


def h1(n,p):
    return {z for z in range(p) if n*z % p == 0}


def main():
    primes=(2,3,5,7,11)
    total=0
    rejected=0
    for p in primes:
        for n in range(1,73):
            for m in divisors(n):
                q=n//m
                for d in divisors(n):
                    old={z for z in h1(n,p) if d*z%p==0}
                    lcm=m*d//gcd(m,d)
                    new={y for y in h1(q,p) if (lcm//m)*y%p==0}
                    image={m*z%p for z in old}
                    if m%p:
                        assert image==new,(p,n,m,d,old,image,new)
                        assert len(old)==len(new)
                        total+=1
                    elif image != new or len(old)!=len(new):
                        rejected+=1
    # Explicit failed full H1 restriction when p divides subgroup index
    p,n,m,d=3,3,3,3
    old={z for z in h1(n,p) if d*z%p==0}
    new={y for y in h1(n//m,p) if (m*d//gcd(m,d)//m)*y%p==0}
    assert old=={0,1,2} and new=={0}
    print(f"PASS {total} prime-to-index local kernel comparisons; {rejected} excluded-index failures; C3/F3 witness")


if __name__=="__main__":
    main()
